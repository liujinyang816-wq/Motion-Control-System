/**
 ******************************************************************************
 * @file           : types.h
 * @brief          : 项目通用类型定义
 * ----------------------------------------------------------------------------
 * 定义：
 *   1. bool 类型别名
 *   2. 网络字节序转换宏 (htons/ntohs/htonl/ntohl)
 *
 * 大端转小端 (STM32H7 为小端架构):
 *   - htons/ntohs: 16位字节翻转
 *   - htonl/ntohl: 32位字节翻转
 ******************************************************************************
 */
#ifndef _TYPES_H_
#define _TYPES_H_

#include "stm32h7xx_hal.h"

/** 布尔类型 (使用 unsigned char 节省空间) */
typedef unsigned char bool;

/* ============================================================================
 * 网络字节序转换宏（大端 ↔ 小端）
 * STM32H7 是小端架构，以太网数据为大端
 * ============================================================================ */

/** 16位: Host ↔ Network 字节序转换 */
#define htons(x) ((((x) & 0xff) << 8) | (((x) & 0xff00) >> 8))
#define ntohs(x) htons(x)

/** 32位: Host ↔ Network 字节序转换 */
#define htonl(x) ((((x) & 0xff) << 24) | \
                  (((x) & 0xff00) << 8) | \
                  (((x) & 0xff0000) >> 8) | \
                  (((x) & 0xff000000) >> 24))
#define ntohl(x) htonl(x)

#endif
